package ru.mux.app.nginx

import java.io.File

data class ProxyRule(
    val locationPath: String = "/",
    val proxyPassUrl: String
)

data class NginxConfig(
    val workerProcesses: Int = 1,
    val workerConnections: Int = 1024,
    val port: Int = 8080,
    val serverName: String = "localhost",
    val rootDir: String,
    val indexFile: String = "index.html",
    val proxyRules: List<ProxyRule> = emptyList()
)

class NginxConfigManager(
    private val baseDir: File
) {
    val nginxDir: File by lazy {
        File(baseDir, "nginx").apply {
            if (!exists()) {
                mkdirs()
            }
        }
    }

    val configFile: File
        get() = File(nginxDir, "nginx.conf")

    val htmlDir: File
        get() = File(nginxDir, "html").apply {
            if (!exists()) {
                mkdirs()
            }
        }

    init {
        if (!configFile.exists()) {
            val defaultConfig = NginxConfig(rootDir = htmlDir.absolutePath)
            writeConfig(defaultConfig)
            createDefaultIndexFile()
        }
    }

    fun createDefaultIndexFile() {
        val indexFile = File(htmlDir, "index.html")
        if (!indexFile.exists()) {
            indexFile.writeText(
                """
                <!DOCTYPE html>
                <html>
                <head><title>Mux Web Server</title></head>
                <body>
                <h1>Welcome to Mux Nginx Server</h1>
                <p>Server is up and running!</p>
                </body>
                </html>
                """.trimIndent()
            )
        }
    }

    fun generateConfigText(config: NginxConfig): String {
        val proxyRulesBlock = if (config.proxyRules.isNotEmpty()) {
            "\n" + config.proxyRules.joinToString("\n") { rule ->
                """        location ${rule.locationPath} {
            proxy_pass ${rule.proxyPassUrl};
            proxy_set_header Host ${'$'}host;
            proxy_set_header X-Real-IP ${'$'}remote_addr;
        }"""
            }
        } else ""

        return """
# Generated by Mux NginxConfigManager
worker_processes ${config.workerProcesses};

events {
    worker_connections ${config.workerConnections};
}

http {
    include mime.types;
    default_type application/octet-stream;
    sendfile on;
    keepalive_timeout 65;

    server {
        listen ${config.port};
        server_name ${config.serverName};

        location / {
            root ${config.rootDir};
            index ${config.indexFile};
        }$proxyRulesBlock
    }
}
        """.trimIndent()
    }

    fun writeConfig(config: NginxConfig): File {
        val content = generateConfigText(config)
        configFile.writeText(content)
        return configFile
    }

    fun writeRawConfig(content: String): File {
        configFile.writeText(content)
        return configFile
    }

    fun readConfig(): String {
        return if (configFile.exists()) {
            configFile.readText()
        } else {
            ""
        }
    }

    fun parseConfig(): NginxConfig {
        val text = readConfig()
        val portRegex = Regex("""listen\s+(\d+);""")
        val serverNameRegex = Regex("""server_name\s+([^;]+);""")
        val rootRegex = Regex("""root\s+([^;]+);""")
        val workerProcessesRegex = Regex("""worker_processes\s+(\d+);""")
        val workerConnRegex = Regex("""worker_connections\s+(\d+);""")
        val proxyPassRegex = Regex("""location\s+([^\s{]+)\s*\{[^}]*proxy_pass\s+([^;]+);""")

        val port = portRegex.find(text)?.groupValues?.get(1)?.toIntOrNull() ?: 8080
        val serverName = serverNameRegex.find(text)?.groupValues?.get(1)?.trim() ?: "localhost"
        val rootDir = rootRegex.find(text)?.groupValues?.get(1)?.trim() ?: htmlDir.absolutePath
        val workerProcesses = workerProcessesRegex.find(text)?.groupValues?.get(1)?.toIntOrNull() ?: 1
        val workerConnections = workerConnRegex.find(text)?.groupValues?.get(1)?.toIntOrNull() ?: 1024

        val proxyRules = proxyPassRegex.findAll(text).map { match ->
            ProxyRule(
                locationPath = match.groupValues[1].trim(),
                proxyPassUrl = match.groupValues[2].trim()
            )
        }.toList()

        return NginxConfig(
            workerProcesses = workerProcesses,
            workerConnections = workerConnections,
            port = port,
            serverName = serverName,
            rootDir = rootDir,
            proxyRules = proxyRules
        )
    }

    fun updatePort(newPort: Int): NginxConfig {
        val current = parseConfig()
        val updated = current.copy(port = newPort)
        writeConfig(updated)
        return updated
    }

    fun updateServerName(newServerName: String): NginxConfig {
        val current = parseConfig()
        val updated = current.copy(serverName = newServerName)
        writeConfig(updated)
        return updated
    }

    fun addProxyRule(locationPath: String, proxyPassUrl: String): NginxConfig {
        val current = parseConfig()
        val updatedRules = current.proxyRules + ProxyRule(locationPath, proxyPassUrl)
        val updated = current.copy(proxyRules = updatedRules)
        writeConfig(updated)
        return updated
    }

    fun validateConfig(configContent: String): Boolean {
        if (configContent.isBlank()) return false

        var braceCount = 0
        for (char in configContent) {
            when (char) {
                '{' -> braceCount++
                '}' -> braceCount--
            }
            if (braceCount < 0) return false
        }
        if (braceCount != 0) return false

        if (!configContent.contains("http {")) return false
        if (!configContent.contains("server {")) return false
        if (!configContent.contains(Regex("""listen\s+\d+;"""))) return false

        return true
    }
}
